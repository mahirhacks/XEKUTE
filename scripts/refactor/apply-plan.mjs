#!/usr/bin/env node
// Applies a module plan to the renderer root one module at a time. Each step
// runs split-module.mjs, then the UI build and the test suite, and commits only
// when both pass; the first failure stops the run with the tree left as is.
// Usage: node scripts/refactor/apply-plan.mjs <plan.json> [startIndex]
import fs from "node:fs";
import { execSync } from "node:child_process";

const [planFile, startArg] = process.argv.slice(2);
const plan = JSON.parse(fs.readFileSync(planFile, "utf8")).filter(entry => entry.module !== "KEEP_IN_ROOT");
const run = (command, options = {}) => execSync(command, { stdio: "pipe", encoding: "utf8", maxBuffer: 1 << 28, ...options });

for (let index = Number(startArg || 0); index < plan.length; index++) {
  const { module, why, names } = plan[index];
  const label = `[${index + 1}/${plan.length}] ${module}`;
  console.log(`${label}: moving ${names.length} names`);
  console.log(run(`node scripts/refactor/split-module.mjs src/ui/bootstrap.js ${module} --names ${names.join(",")}`).trim());
  try {
    run("npm run build:ui");
  } catch (error) {
    console.log(`${label}: build failed\n${String(error.stdout).split("\n").filter(line => /error|Error/.test(line)).slice(0, 20).join("\n")}`);
    process.exit(1);
  }
  // A few process and socket tests flake under load; a real break fails twice.
  for (let attempt = 1; ; attempt++) {
    try {
      run("npm test");
      break;
    } catch (error) {
      const out = String(error.stdout);
      const failures = out.slice(out.indexOf("✖ failing tests:")).slice(0, 4000);
      if (attempt === 1) {
        console.log(`${label}: retrying tests after a failure\n${failures.split("\n").filter(line => line.startsWith("test at")).join("\n")}`);
        continue;
      }
      console.log(`${label}: tests failed\n${failures}`);
      process.exit(1);
    }
  }
  run("git add -A src/ui test/helpers/renderer-source.js");
  const message = `Extract ${module.replace(/^src\/ui\//, "")} from bootstrap.js\n\n${why}\n\nGenerated by scripts/refactor/split-module.mjs.\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>`;
  fs.writeFileSync(".git/SPLIT_MSG", message);
  run("git commit -q -F .git/SPLIT_MSG");
  console.log(`${label}: committed (${run("wc -l < src/ui/bootstrap.js").trim()} root lines)`);
}
