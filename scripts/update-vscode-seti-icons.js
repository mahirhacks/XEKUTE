"use strict";

const fs = require("node:fs");
const path = require("node:path");

const VSCODE_SETI_REF = "634e10ede06cc080795b3a34543b0dc8aa513d9a";
const VSCODE_SETI_ROOT = `https://raw.githubusercontent.com/microsoft/vscode/${VSCODE_SETI_REF}/extensions/theme-seti`;
const projectRoot = path.resolve(__dirname, "..");
const assetDirectory = path.join(projectRoot, "src", "ui", "assets", "vscode-seti");
const modulePath = path.join(projectRoot, "src", "ui", "features", "project", "seti-icon-theme.js");

async function download(relativePath, responseType = "text") {
  const response = await fetch(`${VSCODE_SETI_ROOT}/${relativePath}`);
  if (!response.ok) {
    throw new Error(`Could not download VS Code Seti asset ${relativePath}: HTTP ${response.status}`);
  }
  return responseType === "buffer"
    ? Buffer.from(await response.arrayBuffer())
    : response.text();
}

function resolveIcon(theme, iconId) {
  const definition = theme.iconDefinitions?.[iconId] || theme.iconDefinitions?.[theme.file];
  const codePoint = Number.parseInt(String(definition?.fontCharacter || "\\E023").replace(/^\\/, ""), 16);
  return [String.fromCodePoint(codePoint), definition?.fontColor || "#d4d7d6"];
}

function materializeAssociations(theme, associations = {}) {
  return Object.fromEntries(
    Object.entries(associations)
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([key, iconId]) => [key.toLowerCase(), resolveIcon(theme, iconId)]),
  );
}

function parseStringArray(source, property) {
  const match = source.match(new RegExp(`${property}:\\s*(\\[[^\\]]*\\])`));
  if (!match) return [];
  try {
    return JSON.parse(match[1]);
  } catch {
    return [];
  }
}

function monacoLanguageAssociations(theme) {
  const definitionsRoot = path.join(projectRoot, "node_modules", "monaco-editor", "esm", "vs", "languages", "definitions");
  const extensionIds = {};
  const fileNameIds = {};
  const languageAliases = { pug: "jade", shell: "shellscript" };
  if (fs.existsSync(definitionsRoot)) {
    for (const directory of fs.readdirSync(definitionsRoot, { withFileTypes: true })) {
      if (!directory.isDirectory()) continue;
      const registerPath = path.join(definitionsRoot, directory.name, "register.js");
      if (!fs.existsSync(registerPath)) continue;
      const source = fs.readFileSync(registerPath, "utf8");
      const languageMatch = source.match(/id:\s*"([^"]+)"/);
      if (!languageMatch) continue;
      const languageId = languageAliases[languageMatch[1]] || languageMatch[1];
      if (!theme.languageIds?.[languageId]) continue;
      for (const extension of parseStringArray(source, "extensions")) {
        extensionIds[String(extension).replace(/^\./, "").toLowerCase()] = languageId;
      }
      for (const fileName of parseStringArray(source, "filenames")) {
        fileNameIds[String(fileName).toLowerCase()] = languageId;
      }
    }
  }

  Object.assign(extensionIds, {
    cjs: "javascript", cts: "typescript", env: "dotenv", gitignore: "ignore",
    js: "javascript", json: "json", jsonc: "jsonc", jsonl: "jsonl",
    jsx: "javascriptreact", md: "markdown", mjs: "javascript", mts: "typescript",
    psd1: "powershell", psm1: "powershell", ts: "typescript", tsx: "typescriptreact",
  });
  Object.assign(fileNameIds, {
    ".env": "dotenv", ".gitignore": "ignore", "dockerfile": "dockerfile", "makefile": "makefile",
  });

  const materializeLanguageIds = (associations) => Object.fromEntries(
    Object.entries(associations)
      .filter(([, languageId]) => theme.languageIds?.[languageId])
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([key, languageId]) => [key, resolveIcon(theme, theme.languageIds[languageId])]),
  );
  return {
    fileExtensions: materializeLanguageIds(extensionIds),
    fileNames: materializeLanguageIds(fileNameIds),
  };
}

function generatedModule(theme) {
  const defaultIcon = resolveIcon(theme, theme.file);
  const fileExtensions = materializeAssociations(theme, theme.fileExtensions);
  const fileNames = materializeAssociations(theme, theme.fileNames);
  const languageAssociations = monacoLanguageAssociations(theme);
  return `/* Generated by scripts/update-vscode-seti-icons.js. Do not edit by hand.\n` +
    ` * Source: microsoft/vscode@${VSCODE_SETI_REF}/extensions/theme-seti */\n` +
    `(function initSetiIconTheme(root, factory) {\n` +
    `  const api = factory();\n` +
    `  if (typeof module === "object" && module.exports) module.exports = api;\n` +
    `  if (root) root.XekuteSetiIconTheme = api;\n` +
    `})(typeof globalThis !== "undefined" ? globalThis : this, function createSetiIconTheme() {\n` +
    `  const DEFAULT_ICON = ${JSON.stringify(defaultIcon)};\n` +
    `  const FILE_EXTENSIONS = ${JSON.stringify(fileExtensions)};\n` +
    `  const FILE_NAMES = ${JSON.stringify(fileNames)};\n\n` +
    `  const LANGUAGE_EXTENSIONS = ${JSON.stringify(languageAssociations.fileExtensions)};\n` +
    `  const LANGUAGE_FILE_NAMES = ${JSON.stringify(languageAssociations.fileNames)};\n\n` +
    `  function iconForFile(value = "") {\n` +
    `    const fileName = String(value).replace(/\\\\/g, "/").split("/").pop().toLowerCase();\n` +
    `    const namedIcon = FILE_NAMES[fileName] || LANGUAGE_FILE_NAMES[fileName];\n` +
    `    if (namedIcon) return { glyph: namedIcon[0], color: namedIcon[1] };\n` +
    `    const segments = fileName.split(".");\n` +
    `    for (let index = 1; index < segments.length; index += 1) {\n` +
    `      const extensionIcon = FILE_EXTENSIONS[segments.slice(index).join(".")];\n` +
    `      if (extensionIcon) return { glyph: extensionIcon[0], color: extensionIcon[1] };\n` +
    `    }\n` +
    `    for (let index = 1; index < segments.length; index += 1) {\n` +
    `      const languageIcon = LANGUAGE_EXTENSIONS[segments.slice(index).join(".")];\n` +
    `      if (languageIcon) return { glyph: languageIcon[0], color: languageIcon[1] };\n` +
    `    }\n` +
    `    return { glyph: DEFAULT_ICON[0], color: DEFAULT_ICON[1] };\n` +
    `  }\n\n` +
    `  return Object.freeze({ iconForFile, sourceRef: ${JSON.stringify(VSCODE_SETI_REF)} });\n` +
    `});\n`;
}

async function main() {
  const [themeText, font, notice] = await Promise.all([
    download("icons/vs-seti-icon-theme.json"),
    download("icons/seti.woff", "buffer"),
    download("ThirdPartyNotices.txt"),
  ]);
  const theme = JSON.parse(themeText);
  fs.mkdirSync(assetDirectory, { recursive: true });
  fs.writeFileSync(path.join(assetDirectory, "seti.woff"), font);
  fs.writeFileSync(path.join(assetDirectory, "ThirdPartyNotices.txt"), notice, "utf8");
  fs.writeFileSync(modulePath, generatedModule(theme), "utf8");
  console.log(`Updated VS Code Seti icons from ${VSCODE_SETI_REF}.`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
